"""Verify all reported AGENTRUN results against saved artifacts.

Reads results/eval_results_{base,v1,e4,v2}.json, checks internal
consistency (tally == reported), cross-condition benchmark invariance
(task IDs), and per-task transitions. Emits results_verified.csv,
results_verified.json, and RESULTS_VERIFIED.md.
"""
import json, csv, os

RESULTS = os.path.dirname(os.path.abspath(__file__))
CONDITIONS = [
    ("Base", "eval_results_base.json"),
    ("V1",   "eval_results_v1.json"),
    ("E4",   "eval_results_e4.json"),
    ("V2",   "eval_results_v2.json"),
]

data = {}
issues = []
for cond, fname in CONDITIONS:
    path = os.path.join(RESULTS, fname)
    with open(path) as f:
        d = json.load(f)
    rows = d["results"]
    tally = sum(1 for r in rows if r.get("success") or r.get("passed"))
    reported = d.get("passed")
    total = d.get("total") or d.get("total_tasks")
    ok_tally = (tally == reported)
    ok_total = (len(rows) == total)
    if not ok_tally:
        issues.append(f"{cond}: tally {tally} != reported passed {reported}")
    if not ok_total:
        issues.append(f"{cond}: {len(rows)} results != total {total}")
    data[cond] = {
        "file": f"results/{fname}",
        "passed": reported,
        "total": total,
        "tally": tally,
        "tally_matches": ok_tally,
        "rows_match_total": ok_total,
        "pct": round(100.0 * reported / total, 1),
        "tasks": {r["task_id"]: bool(r.get("success") or r.get("passed")) for r in rows},
        "has_traces": any(r.get("tool_calls") for r in rows),
    }

# benchmark invariance: identical task ID sets across conditions
task_sets = {c: set(v["tasks"]) for c, v in data.items()}
base_ids = sorted(task_sets["Base"])
invariant = all(s == task_sets["Base"] for s in task_sets.values())
if not invariant:
    for c, s in task_sets.items():
        if s != task_sets["Base"]:
            issues.append(f"task set mismatch in {c}: "
                          f"extra={sorted(s - task_sets['Base'])} "
                          f"missing={sorted(task_sets['Base'] - s)}")

# per-task cross-condition table
table = []
for tid in base_ids:
    row = {"task_id": tid}
    for c, _ in CONDITIONS:
        row[c] = "PASS" if data[c]["tasks"][tid] else "fail"
    table.append(row)

# transitions V1 -> E4
v1_to_e4 = [(tid, data["V1"]["tasks"][tid], data["E4"]["tasks"][tid])
            for tid in base_ids if data["V1"]["tasks"][tid] != data["E4"]["tasks"][tid]]
# transitions E4 -> V2
e4_to_v2 = [(tid, data["E4"]["tasks"][tid], data["V2"]["tasks"][tid])
            for tid in base_ids if data["E4"]["tasks"][tid] != data["V2"]["tasks"][tid]]

# write CSV
csv_path = os.path.join(RESULTS, "results_verified.csv")
with open(csv_path, "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["task_id", "Base", "V1", "E4", "V2"])
    for r in table:
        w.writerow([r["task_id"], r["Base"], r["V1"], r["E4"], r["V2"]])

summary = {
    "conditions": {c: {k: v for k, v in d.items() if k != "tasks"} for c, d in data.items()},
    "benchmark_task_ids_invariant_across_conditions": invariant,
    "n_tasks": len(base_ids),
    "v1_to_e4_changes": [{"task_id": t, "V1": "PASS" if a else "fail", "E4": "PASS" if b else "fail"} for t, a, b in v1_to_e4],
    "e4_to_v2_changes": [{"task_id": t, "E4": "PASS" if a else "fail", "V2": "PASS" if b else "fail"} for t, a, b in e4_to_v2],
    "issues": issues,
}
with open(os.path.join(RESULTS, "results_verified.json"), "w") as f:
    json.dump(summary, f, indent=2)

# markdown report
lines = ["# RESULTS_VERIFIED.md", "",
 "Programmatic verification of all reported AGENTRUN results against committed artifacts.",
 "Generated by `results/verify_results.py`. Do not edit numbers by hand.", "",
 "## Condition totals (tallied from per-task records)", "",
 "| Condition | Artifact | Passed | Total | Accuracy | Tally matches reported | Traces present |",
 "|---|---|---:|---:|---:|---|---|"]
for c, _ in CONDITIONS:
    d = data[c]
    lines.append(f"| {c} | `{d['file']}` | {d['tally']} | {d['total']} | {d['pct']}% | {'YES' if d['tally_matches'] else 'NO'} | {'YES' if d['has_traces'] else 'NO (pass/fail only)'} |")
lines += ["", f"Benchmark task IDs identical across all four conditions: **{'YES' if invariant else 'NO'}** (n={len(base_ids)}).", "",
 "## Per-task outcomes", "", "| task_id | Base | V1 | E4 | V2 |", "|---|---|---|---|---|"]
for r in table:
    lines.append(f"| {r['task_id']} | {r['Base']} | {r['V1']} | {r['E4']} | {r['V2']} |")
lines += ["", "## V1 -> E4 transitions (parser effect, adapter held constant)", ""]
if v1_to_e4:
    for t, a, b in v1_to_e4:
        lines.append(f"- `{t}`: {'PASS' if a else 'fail'} -> {'PASS' if b else 'fail'}")
else:
    lines.append("- none")
lines += ["", f"Net E4 effect: {sum(1 for _,a,b in v1_to_e4 if not a and b)} recovered, "
          f"{sum(1 for _,a,b in v1_to_e4 if a and not b)} regressed, "
          f"net {data['E4']['passed'] - data['V1']['passed']:+d}.",
          "", "## E4 -> V2 transitions (data effect, parser held constant)", ""]
if e4_to_v2:
    for t, a, b in e4_to_v2:
        lines.append(f"- `{t}`: {'PASS' if a else 'fail'} -> {'PASS' if b else 'fail'}")
else:
    lines.append("- none")
lines += ["", f"Net data effect: {data['V2']['passed'] - data['E4']['passed']:+d}.",
          "", "## Issues", ""]
lines += ([f"- {i}" for i in issues] if issues else ["- None. All tallies match reported values."])
with open(os.path.join(RESULTS, "..", "RESULTS_VERIFIED.md"), "w") as f:
    f.write("\n".join(lines) + "\n")

print(json.dumps({"issues": issues, "invariant": invariant,
                  "totals": {c: data[c]["passed"] for c, _ in CONDITIONS}}, indent=2))
