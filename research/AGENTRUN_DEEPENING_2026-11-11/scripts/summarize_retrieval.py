"""Summarise raw_results/hpc_retrieval_bench/results.jsonl into a table and a figure.

    py -3.11 scripts/summarize_retrieval.py
"""

from __future__ import annotations

import json
import statistics
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
rows = [json.loads(x) for x in (HERE / "raw_results" / "hpc_retrieval_bench" / "results.jsonl")
        .read_text(encoding="utf-8").splitlines() if x.strip()]
g = defaultdict(list)
for r in rows:
    g[(r["retriever"], r["query_style"], r["size"])].append(r)


def ms(vals):
    return f"{statistics.mean(vals):.3f} ± {statistics.pstdev(vals):.3f}" if len(vals) > 1 else f"{vals[0]:.3f}"


order = sorted({k[0] for k in g}, key=lambda n: (not n.startswith("hash"), not n.startswith("bm25"), n))
sizes = sorted({k[2] for k in g})
md = ["# Retrieval at scale (generated by scripts/summarize_retrieval.py)\n",
      "SIT HPC job 4144, node <compute-node>, NVIDIA L40. 300 queries per store (150 single-fact, 150 with an older and a "
      "newer record for the same fact), 3 seeds; mean ± population sd over seeds. `nl` = the user's question as the "
      "query; `kw` = a short keyword query (project name + attribute words).\n"]
for st in ("nl", "kw"):
    md.append(f"\n## Query style: {st}\n")
    md.append("| Retriever | Store size | recall@1 | recall@4 | recall@10 | MRR@10 | both records of a pair in top-4 | "
              "only the OLDER record in top-4 | index build s | records/s | query ms |")
    md.append("|---|---|---|---|---|---|---|---|---|---|---|")
    for name in order:
        for size in sizes:
            x = g.get((name, st, size))
            if not x:
                continue
            m = lambda k, f: ms([r["metrics"][k][f] for r in x])  # noqa: E731
            md.append(f"| {name} | {size} | {m('k1', 'recall')} | {m('k4', 'recall')} | {m('k10', 'recall')} | "
                      f"{m('k10', 'mrr')} | {m('k4', 'pair_both_retrieved')} | {m('k4', 'pair_only_older_retrieved')} | "
                      f"{statistics.mean(r['index_s'] for r in x):.2f} | "
                      f"{statistics.mean(r['records_per_s_index'] for r in x):,.0f} | "
                      f"{statistics.mean(r['query_ms_mean'] for r in x):.2f} |")
peak = [r["gpu_peak_mem_mib"] for r in rows if "gpu_peak_mem_mib" in r]
md.append(f"\nPeak GPU memory allocated by PyTorch during dense encoding: {max(peak):.0f} MiB "
          "(the L40 has 46 GB; this workload uses a small fraction of it).\n")
(HERE / "tables" / "RETRIEVAL_AT_SCALE.md").write_text("\n".join(md), encoding="utf-8")

import matplotlib  # noqa: E402

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

INK, MUTED, GRID, SURFACE = "#0b0b0b", "#898781", "#e1e0d9", "#fcfcfb"
COL = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100"]
keep = [n for n in order if "(cpu)" not in n]
fig, axes = plt.subplots(1, 2, figsize=(11, 4.2), facecolor=SURFACE, sharex=True)
for ax, (field, title) in zip(axes, [("recall", "Recall@4 (gold record in the top 4)"),
                                     ("pair_only_older_retrieved", "Stale exposure@4 (older record shown, newer one not)")]):
    ax.set_facecolor(SURFACE)
    for s_ in ("top", "right", "left"):
        ax.spines[s_].set_visible(False)
    ax.spines["bottom"].set_color("#c3c2b7")
    ax.tick_params(colors=MUTED, length=0, labelsize=9)
    ax.yaxis.grid(True, color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)
    for name, col in zip(keep, COL):
        ys = [statistics.mean(r["metrics"]["k4"][field] for r in g[(name, "nl", s)]) for s in sizes]
        ax.plot(range(len(sizes)), ys, color=col, linewidth=2, marker="o", markersize=7, label=name.split(" (")[0])
        ax.text(len(sizes) - 1 + 0.06, ys[-1], f"{ys[-1]:.2f}", color=INK, fontsize=8, va="center")
    ax.set_xticks(range(len(sizes)))
    ax.set_xticklabels([f"{s:,}" for s in sizes], color=INK)
    ax.set_xlim(-0.2, len(sizes) - 0.6)
    ax.set_ylim(-0.03, 1.05 if field == "recall" else 0.35)
    ax.set_xlabel("Records in the memory store", color=MUTED, fontsize=9)
    ax.set_title(title, loc="left", color=INK, fontsize=10.5)
axes[0].legend(frameon=False, fontsize=8.5, loc="lower left")
fig.suptitle("Natural-language queries; mean of 3 seeds; SIT HPC job 4144", x=0.01, ha="left", color=MUTED,
             fontsize=8.5, y=0.02)
fig.tight_layout()
fig.savefig(HERE / "figures" / "fig4_retrieval_at_scale.png", dpi=170)
print("\n".join(md))
