"""Power analysis for the Phase 3 confirmatory contrasts, from MEASURED Phase 2 agent-level data (CPU).

    python power_phase3.py --tasks ../data/p2val2/p2val2_tasks.jsonl --runs ../raw/p2val2_* \
        --eval3-families 138 --items-per-family 2 --out ../data/POWER_phase3

Method (no assumed effect sizes):
  1. Load the pilot runs with the frozen analysis code (analyze_p2.load_runs; same scoring, missing = failure).
  2. For each pre-registered contrast X-Y, compute the task-level paired difference per (model, task),
     i.e. exactly the unit analysed in Phase 3, and group the tasks by category.
  3. Simulate eval3: for each of --eval3-families families (spread evenly over the categories, as the eval3
     skeleton is), draw --items-per-family tasks per model with replacement from the pilot tasks of the same
     category (a stratified family bootstrap: it keeps the measured between-category variance and the
     measured within-category, between-task variance).
  4. Test each simulated data set with the Phase 3 test: two-sided family sign-flip, here in its large-sample
     form z = sum(d_f) / sqrt(sum(d_f^2)) (exact for symmetric sign-flip in the limit; > 100 families).
  5. Power = share of simulations with p < alpha, for alpha = 0.05 / k (the strictest Holm step over k
     primary contrasts) and alpha = 0.05; at the measured effect, at half of it (effect shrinkage between
     development and confirmation), and the smallest multiple of the measured effect with power >= 0.8.
Outputs <out>.json and <out>.md.
"""
from __future__ import annotations

import argparse
import json
import math
import random
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import analyze_p2 as az  # noqa: E402  (frozen; imported, not modified)


def phi(x):
    return 0.5 * (1 + math.erf(x / math.sqrt(2)))


def task_diffs(rows, a, b, models):
    diffs, fam_of = az.paired([r for r in rows if r["model"] in models], a, b)[0], {}
    cat = {}
    for r in rows:
        cat[(r["model"], r["task_id"])] = r["scenario"]
    by_cat = defaultdict(lambda: defaultdict(list))
    for (m, tid), d in diffs.items():
        by_cat[cat[(m, tid)]][tid].append((m, d))
    return diffs, by_cat


def simulate(by_cat, models, n_fam, k_items, scale, alphas, n_sim, seed):
    rng = random.Random(seed)
    cats = sorted(by_cat)
    mu = {}
    all_d = [d for c in cats for t in by_cat[c].values() for _, d in t]
    grand = sum(all_d) / len(all_d)
    hits = {a: 0 for a in alphas}
    for _ in range(n_sim):
        fams = []
        for f in range(n_fam):
            c = cats[f % len(cats)]
            tids = list(by_cat[c])
            s = 0.0
            for _ in range(k_items):
                t = by_cat[c][rng.choice(tids)]
                for _, d in t:
                    s += grand * (scale - 1) + d  # shift the whole distribution to `scale` x the measured mean
            fams.append(s)
        ss = sum(x * x for x in fams)
        if ss == 0:
            continue
        z = abs(sum(fams)) / math.sqrt(ss)
        p = 2 * (1 - phi(z))
        for a in alphas:
            hits[a] += p < a
    del mu
    return {str(a): round(h / n_sim, 3) for a, h in hits.items()}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tasks", nargs="+", required=True)
    ap.add_argument("--runs", nargs="+", required=True)
    ap.add_argument("--contrasts", default="EBG-RT,EBG-T,EBG-LG,EBG-B")
    ap.add_argument("--models", default="Qwen/Qwen2.5-3B-Instruct,Qwen/Qwen2.5-7B-Instruct,meta-llama/Llama-3.1-8B-Instruct")
    ap.add_argument("--eval3-families", type=int, required=True)
    ap.add_argument("--items-per-family", type=int, default=2)
    ap.add_argument("--n-sim", type=int, default=2000)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    tasks = {}
    for p in a.tasks:
        tasks.update({t["task_id"]: t for t in az.load_jsonl(p)})
    rows = az.load_runs(tasks, a.runs)
    models = a.models.split(",")
    k = len(a.contrasts.split(","))
    alphas = [round(0.05 / k, 4), 0.05]
    out = {"pilot_tasks": len(tasks), "pilot_runs": len(rows), "models": models, "eval3_families": a.eval3_families,
           "items_per_family": a.items_per_family, "alphas": alphas, "n_sim": a.n_sim, "contrasts": {}}
    md = ["# Phase 3 power analysis (from measured Phase 2 agent-level data)\n",
          f"Pilot: {len(tasks)} tasks, {len(rows)} scored runs, models {', '.join(m.split('/')[-1] for m in models)}. "
          f"eval3 design: {a.eval3_families} families x {a.items_per_family} items x {len(models)} models. "
          f"alpha {alphas[0]} (strictest Holm step over {k}) and 0.05. {a.n_sim} simulations each. "
          "Generated by `scripts/power_phase3.py`.\n",
          "| Contrast | pilot task pairs | measured diff pp | family-level SD of task diffs (pp) | power @measured (Holm a / 0.05) | "
          "power @half (Holm a / 0.05) | smallest multiple of measured effect with power >= 0.8 at Holm a |",
          "|---|---|---|---|---|---|---|"]
    for i, spec in enumerate(a.contrasts.split(",")):
        x, y = spec.split("-", 1)
        diffs, by_cat = task_diffs(rows, x, y, models)
        if not diffs:
            continue
        vals = list(diffs.values())
        mean = sum(vals) / len(vals)
        sd = math.sqrt(sum((v - mean) ** 2 for v in vals) / max(1, len(vals) - 1))
        full = simulate(by_cat, models, a.eval3_families, a.items_per_family, 1.0, alphas, a.n_sim, 10 + i)
        half = simulate(by_cat, models, a.eval3_families, a.items_per_family, 0.5, alphas, a.n_sim, 20 + i)
        mult = None
        for m10 in range(1, 31):
            if mean == 0:
                break
            pw = simulate(by_cat, models, a.eval3_families, a.items_per_family, m10 / 10, alphas[:1], a.n_sim // 4, 30 + i)
            if pw[str(alphas[0])] >= 0.8:
                mult = m10 / 10
                break
        out["contrasts"][spec] = {"n_task_pairs": len(vals), "mean_diff_pp": round(100 * mean, 1), "sd_pp": round(100 * sd, 1),
                                  "power_measured": full, "power_half": half, "mde_multiple_80": mult,
                                  "mde_pp_80": round(100 * mean * mult, 1) if mult else None}
        md.append(f"| {spec} | {len(vals)} | {100 * mean:+.1f} | {100 * sd:.1f} | {full[str(alphas[0])]} / {full['0.05']} | "
                  f"{half[str(alphas[0])]} / {half['0.05']} | {mult if mult else '> 3'}"
                  f"{f' ({100 * mean * mult:+.1f} pp)' if mult else ''} |")
    Path(a.out + ".json").write_text(json.dumps(out, indent=1) + "\n", encoding="utf-8")
    Path(a.out + ".md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
