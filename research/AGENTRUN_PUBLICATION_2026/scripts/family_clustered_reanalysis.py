"""Family-clustered reanalysis of Campaign 2 (statistical audit, 2026-11-13).

The eval2 split's 96 tasks are template instantiations: 6 scenarios x 2-6
variants = 22 scenario-variant families. The canonical analysis
(scripts/analyze_c2.py in AGENTRUN_DEEPENING_2026-11-11) bootstraps over
tasks (96 clusters) and, when pooling two models, over task-x-model (192
clusters). This script recomputes the headline paired contrasts with the
bootstrap clustered on scenario-variant FAMILY (22 clusters; pooling keeps
family as the cluster, not family-x-model), which is the conservative unit
of independence. McNemar is unchanged (it tests marginal homogeneity on
pairs and is reported alongside, not relied on, for clustered data).

    py -3.11 family_clustered_reanalysis.py

Reads the raw run files of AGENTRUN_DEEPENING_2026-11-11; writes
../analysis/family_clustered_results.md and .json next to it.
"""

from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
DEEP = HERE.parent.parent / "AGENTRUN_DEEPENING_2026-11-11"
sys.path.insert(0, str(DEEP / "scripts"))
import memlab  # noqa: E402
from analyze import mcnemar_exact, pfmt  # noqa: E402

TASKS = {}
for line in (DEEP / "benchmark" / "eval2.jsonl").read_text(encoding="utf-8").splitlines():
    if line.strip():
        t = json.loads(line)
        TASKS[t["task_id"]] = t

rng = np.random.default_rng(20261113)
N_BOOT = 4000


def load(run_id):
    p = DEEP / "raw_results" / run_id / "runs.jsonl"
    if not p.exists():
        return None
    rows = {}
    for line in p.read_text(encoding="utf-8").splitlines():
        if line.strip():
            r = json.loads(line)
            s = memlab.score_run(TASKS[r["task_id"]], r)
            rows[(r["task_id"], r["config"])] = s
    return rows


def family(task_id):
    t = TASKS[task_id]
    return f"{t['scenario']}|{t['variant']}"


def paired_family(a_rows, b_rows, keys):
    """a minus b on shared keys; bootstrap over scenario-variant families.

    Keys are (task_id, config) or (task_id|tag, config) when pooled; the
    family of 'task|tag' is the family of 'task' (models share clusters).
    """
    keys = [k for k in keys if k in a_rows and k in b_rows]
    if not keys:
        return None
    d = np.array([int(a_rows[k]["success"]) - int(b_rows[k]["success"]) for k in keys])
    by_fam = defaultdict(list)
    for i, k in enumerate(keys):
        tid = k[0].split("|")[0]
        by_fam[family(tid)].append(i)
    fams = sorted(by_fam)
    boots = []
    for _ in range(N_BOOT):
        idx = [i for f in rng.choice(len(fams), len(fams)) for i in by_fam[fams[f]]]
        boots.append(d[idx].mean())
    lo, hi = np.percentile(boots, [2.5, 97.5])
    plus, minus = int((d == 1).sum()), int((d == -1).sum())
    return {"n_pairs": len(keys), "n_families": len(fams), "diff_pp": 100 * float(d.mean()),
            "ci_lo": 100 * float(lo), "ci_hi": 100 * float(hi),
            "a_only": plus, "b_only": minus, "mcnemar_p": mcnemar_exact(plus, minus)}


def cfg_pairs(rows, a, b):
    keys = [t for (t, c) in rows if c == a and (t, b) in rows]
    A = {(t, "x"): rows[(t, a)] for t in keys}
    B = {(t, "x"): rows[(t, b)] for t in keys}
    return paired_family(A, B, list(A))


def merge(*runs):
    out = {}
    for tag, rows in runs:
        if rows:
            for (t, c), r in rows.items():
                out[(t + "|" + tag, c)] = r
    return out


def row(label, c):
    if c is None:
        return f"| {label} | - | - | - | - | - | - |"
    return (f"| {label} | {c['n_pairs']} | {c['n_families']} | {c['diff_pp']:+.1f} "
            f"| [{c['ci_lo']:+.1f}, {c['ci_hi']:+.1f}] | {c['a_only']} / {c['b_only']} | {pfmt(c['mcnemar_p'])} |")


def main() -> int:
    R = {i: load(i) for i in
         ["c2_qwen25_7b_v1", "c2_qwen3_8b_v1", "c2_qwen25_7b_v2", "c2_qwen3_8b_v2",
          "c2_qwen25_14b_v1", "c2_qwen25_14b_v2", "c2_qwen25_3b_v1", "c2_qwen25_3b_v2",
          "c2_qwen25_7b_v2_hash_pad2000", "c2_qwen25_7b_v2_bm25_pad2000"]}

    md = ["# Family-clustered reanalysis (bootstrap over 22 scenario-variant families)\n",
          "Same point estimates as the canonical analysis; CIs are clustered on the",
          "scenario-variant family instead of the task. Generated by",
          "`scripts/family_clustered_reanalysis.py`. McNemar p is the unclustered pair test,",
          "shown for continuity; the clustered CI is the inferential criterion here.\n",
          "| Comparison | n pairs | n families | diff (pp) | 95% family-bootstrap CI | discordant | McNemar p |",
          "|---|---|---|---|---|---|---|"]
    res = {}

    pooled_v1 = merge(("q25", R["c2_qwen25_7b_v1"]), ("q3", R["c2_qwen3_8b_v1"]))
    pooled_v2 = merge(("q25", R["c2_qwen25_7b_v2"]), ("q3", R["c2_qwen3_8b_v2"]))
    for name, a, b in [("v1 pooled: B - A (memory)", "B", "A"), ("v1 pooled: C - B (verifier)", "C", "B"),
                       ("v1 pooled: D - C (provenance)", "D", "C"), ("v1 pooled: E - D (gate)", "E", "D"),
                       ("v1 pooled: E - B (all three)", "E", "B")]:
        c = cfg_pairs(pooled_v1, a, b)
        res[name] = c
        md.append(row(name, c))
    for name, a, b in [("v2 pooled: B - A (memory)", "B", "A"), ("v2 pooled: C - B (verifier)", "C", "B"),
                       ("v2 pooled: D - C (provenance)", "D", "C"), ("v2 pooled: E - D (gate)", "E", "D")]:
        c = cfg_pairs(pooled_v2, a, b)
        res[name] = c
        md.append(row(name, c))

    # harness effect per model (v2 - v1, all configs)
    for name, a, b in [("Qwen2.5-7B: v2 - v1", "c2_qwen25_7b_v2", "c2_qwen25_7b_v1"),
                       ("Qwen3-8B: v2 - v1", "c2_qwen3_8b_v2", "c2_qwen3_8b_v1")]:
        c = paired_family(R[a], R[b], list(R[b]))
        res[name] = c
        md.append(row(name, c))

    # per-model component effects at 7B (the headline model)
    for name, a, b in [("7B v2: C - B (verifier)", "C", "B"), ("7B v2: E - D (gate)", "E", "D"),
                       ("7B v1: D - C (provenance)", "D", "C"), ("7B v2: D - C (provenance)", "D", "C")]:
        rows = R["c2_qwen25_7b_v2" if "v2" in name else "c2_qwen25_7b_v1"]
        c = cfg_pairs(rows, a, b)
        res[name] = c
        md.append(row(name, c))

    # retrieval (S1-S4 only, configs B/D/E; these runs only contain those)
    base = {k: v for k, v in R["c2_qwen25_7b_v2"].items()
            if k[1] in "BDE" and TASKS[k[0]]["scenario"][:2] in ("S1", "S2", "S3", "S4")}
    for name, a_id, ref in [("hash+2000 - no padding", "c2_qwen25_7b_v2_hash_pad2000", base),
                            ("BM25+2000 - hash+2000", "c2_qwen25_7b_v2_bm25_pad2000",
                             R["c2_qwen25_7b_v2_hash_pad2000"])]:
        c = paired_family(R[a_id], ref, list(R[a_id]))
        res[name] = c
        md.append(row(name, c))

    # size sweep: memory and gate effects at 3B and 14B
    for sz in ("3b", "14b"):
        for name, a, b in [(f"{sz} v2: B - A (memory)", "B", "A"), (f"{sz} v2: E - D (gate)", "E", "D")]:
            c = cfg_pairs(R[f"c2_qwen25_{sz}_v2"], a, b)
            res[name] = c
            md.append(row(name, c))

    out = HERE.parent / "analysis"
    out.mkdir(exist_ok=True)
    (out / "family_clustered_results.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    (out / "family_clustered_results.json").write_text(json.dumps(res, indent=1), encoding="utf-8")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
