"""Assemble the Phase 3 deliverables from the frozen analysis outputs. No new statistics: every number is read from
the JSON written by PHASE2/scripts/analyze_p2.py (frozen) and PHASE3/scripts/phase3_metrics.py, or from run manifests,
DONE markers and Slurm log start/exit lines (never per-task outcome lines).

    python build_reports.py --src ANALYSIS --dest . --cells <run dirs...> [--logs logs] [--dry]
    DRY test:  python build_reports.py --src ANALYSIS/DRYRUN --dest ANALYSIS/DRYRUN/reports --cells ../PHASE2/raw/p2val2_*_greedy --dry

Writes to --dest:
  PHASE3_EXECUTION_LOG.md         per-cell provenance, timing, completeness (+ results/execution.csv)
  PHASE3_COMPARISON_TABLES.md     model x configuration, category x configuration, decoding, secondary cells, metrics
  PHASE3_ABLATION_RESULTS.md      component-ablation contrasts (exploratory, BH) with descriptive measures
  PHASE3_STATISTICAL_ANALYSIS.md  H-primary and S1-S3 (Holm), S4 harm, exploratory E1-E5, per-model, sensitivity, secondary
  PHASE3_FAILURE_TABLES.md        outcome categories per configuration (input to the hand-written failure analysis)
  PHASE3_DECISIONS.json           mechanical verdicts for each pre-registered hypothesis (PREREGISTRATION.md section 2)
  results/*.csv                   machine-readable versions of every table
Interpretation (PHASE3_FAILURE_ANALYSIS.md, PHASE3_FINAL_REPORT.md) is written by a person from these tables.
"""
