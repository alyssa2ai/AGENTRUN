"""Auto-filled manuscript results draft from the verified Phase 3 outputs (no interpretation, no new statistics).

    python write_results_section.py --p3 <PHASE3 dir> --out <PHASE4/manuscript/07_results_AUTO.md>

Every number comes from PHASE3_DECISIONS.json and results/*.csv written by build_reports.py. Sentences are templated
from the pre-registered decision rules; discussion and interpretation are left to the authors (marked TODO).
"""
import argparse, csv, json
from pathlib import Path


def rows(p):
    return list(csv.DictReader(open(p, encoding="utf-8"))) if p.exists() else []


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--p3", required=True); ap.add_argument("--out", required=True)
    a = ap.parse_args(); p3 = Path(a.p3); res = p3 / "results"
    dec = json.loads((p3 / "PHASE3_DECISIONS.json").read_text(encoding="utf-8"))
    con = rows(res / "contrasts_primary_cells.csv")
    pm = rows(res / "per_model_config.csv")
    ex = rows(res / "execution.csv")
    L = ["# 7 Results (AUTO-GENERATED DRAFT from verified Phase 3 outputs)", "",
         "> Generated by `PHASE3/scripts/write_results_section.py` inside the HPC finalization job. Numbers are copied "
         "from `PHASE3/PHASE3_DECISIONS.json` and `PHASE3/results/*.csv`; verdicts follow PREREGISTRATION.md section 2 "
         "mechanically. Interpretation and discussion are TODO for the authors.", "",
         "## 7.1 Analysis sample", "",
         f"The confirmatory analysis pools the primary models {', '.join(dec['models_pooled'])} over greedy decoding and "
         f"three T=0.7 seeds: {dec['n_tasks']} eval3 tasks in {dec['n_families']} families, {dec['n_rows']} scored runs. "
         f"{sum(r['status'] == 'DONE' for r in ex)} of {len(ex)} cells completed; missing pairs and harness errors count "
         "as failures.", "", "## 7.2 Pre-registered hypotheses", "",
         "| Hypothesis | Contrast | Difference (pp) | 95% CI | Holm-adjusted p | Verdict |", "|---|---|---|---|---|---|"]
    for k, v in dec["hypotheses"].items():
        if k != "S4":
            L.append(f"| {k} | {v['contrast']} | {v['diff_pp']} | {v['ci95_pp']} | {v['p_holm']:.4g} | {v['verdict']} |"
                     if v.get("p_holm") is not None else f"| {k} | {v['contrast']} | {v['diff_pp']} | {v['ci95_pp']} | - | {v['verdict']} |")
    for k, v in dec["hypotheses"].items():
        if k == "S4":
            continue
        word = "higher" if v["diff_pp"] > 0 else "lower" if v["diff_pp"] < 0 else "equal"
        L += ["", f"**{k} ({v['contrast']}).** Task success under EBG was {abs(v['diff_pp'])} percentage points {word} "
              f"than under {v['contrast'].split('-', 1)[1]} (95% family-bootstrap CI {v['ci95_pp']}; two-sided sign-flip "
              f"permutation p = {v['p']:.4g}, Holm-adjusted p = {v['p_holm']:.4g}). Pre-registered verdict: {v['verdict']}."
              if v.get("p_holm") is not None else f"**{k}.** {v['verdict']}."]
    if "S4" in dec["hypotheses"]:
        v = dec["hypotheses"]["S4"]
        L += ["", f"**S4 (harm).** The harmful-answer rate differed by {v['diff_pp']} pp between EBG and RT (95% CI "
              f"{v['ci95_pp']}); harmful answers EBG {v['harmful_EBG'][0]}/{v['harmful_EBG'][1]}, RT "
              f"{v['harmful_RT'][0]}/{v['harmful_RT'][1]}; arbitrary picks EBG {v['arbitrary_pick_EBG']}, RT "
              f"{v['arbitrary_pick_RT']}. Verdict: {v['verdict']}."]
    L += ["", "## 7.3 Per-model effects (descriptive, not counted toward the claims)", "",
          "| Contrast | Model | Difference (pp) | 95% CI | Families +/- | Harmful difference (pp) |", "|---|---|---|---|---|---|"]
    for r in con:
        if r["contrast"] in ("EBG-RT", "EBG-T", "EBG-LG", "EBG-B") and r["model"] != "ALL":
            L.append(f"| {r['contrast']} | {r['model']} | {r['diff_pp']} | [{r['ci_lo']}, {r['ci_hi']}] | "
                     f"{r['families_pos']}/{r['families_neg']} | {r['harm_diff_pp']} |")
    L += ["", "## 7.4 Ablations (exploratory, BH)", "", "| Contrast | Difference (pp) | 95% CI | p (BH) | Harmful difference (pp) |",
          "|---|---|---|---|---|"]
    for r in con:
        if r["contrast"] not in ("EBG-RT", "EBG-T", "EBG-LG", "EBG-B") and r["model"] == "ALL":
            L.append(f"| {r['contrast']} | {r['diff_pp']} | [{r['ci_lo']}, {r['ci_hi']}] | {r['p_bh']} | {r['harm_diff_pp']} |")
    L += ["", "## 7.5 Success and harm by configuration (pooled primary models)", "",
          "| Config | Success | Harmful | Over-abstain | Format errors | Step limit | Missing |", "|---|---|---|---|---|---|---|"]
    for r in pm:
        if r["source"] == "primary_cells" and r["model"] == "ALL":
            n = int(r["n"])
            f = lambda k: f"{r[k]} ({100 * int(r[k]) / n:.1f}%)"  # noqa: E731
            L.append(f"| {r['config']} | {f('success')} | {f('harmful')} | {f('over_abstain')} | {f('format_error')} | "
                     f"{f('step_limit')} | {f('missing')} |")
    L += ["", "Sensitivity analyses, secondary cells, per-category and per-decoding tables: `PHASE3/PHASE3_STATISTICAL_ANALYSIS.md`, "
          "`PHASE3/PHASE3_COMPARISON_TABLES.md`.", "", "TODO (authors): interpretation, discussion of model-family and size "
          "differences, gating vs ungated enforcement, failure analysis narrative."]
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote", a.out)


if __name__ == "__main__":
    main()
