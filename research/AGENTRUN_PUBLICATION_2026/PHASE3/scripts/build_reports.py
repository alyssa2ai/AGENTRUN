"""Assemble Phase 3 deliverables from ANALYSIS/ outputs (no new statistics; text blocks are copied from the frozen tools).

    python build_reports.py [--src ANALYSIS] [--dest .]      # DRY: --src ANALYSIS/DRYRUN --dest ANALYSIS/DRYRUN/reports

Writes MODEL_COMPARISON.md, ABLATION_RESULTS.md, STATISTICAL_RESULTS.md, LATENCY_AND_COST.md and an
EXPERIMENT_EXECUTION_LOG.md skeleton from COMPLETENESS.md. FAILURE_ANALYSIS.md and PHASE3_FINAL_REPORT.md need
human interpretation and are written after reading these tables; this script never writes conclusions.
"""
import argparse, re
from pathlib import Path


def section(md, title):
    m = re.search(r"^## " + re.escape(title) + r".*?$(.*?)(?=^## |\Z)", md, re.S | re.M)
    return m.group(1).strip() if m else "(section missing)"


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--src", default="ANALYSIS"); ap.add_argument("--dest", default=".")
    a = ap.parse_args(); s, d = Path(a.src), Path(a.dest); d.mkdir(parents=True, exist_ok=True)
    rd = lambda n: (s / n).read_text(encoding="utf-8") if (s / n).exists() else ""
    conf, met, comp = rd("CONFIRMATORY_primary_cells.md"), rd("METRICS.md"), rd("COMPLETENESS.md")
    sens, sec = rd("SENSITIVITY_annotator_agreed.md"), rd("SECONDARY_cells.md")
    note = "Generated by `PHASE3/scripts/build_reports.py` from the frozen analysis outputs; denominators are in the tables; missing runs count as failures.\n\n"
    contrasts = section(conf, "Paired contrasts")
    rows = contrasts.splitlines()
    abl = [r for r in rows[:2]] + [r for r in rows[2:] if re.search(r"EBG-EB |EBG-EBG-all|EBG-EBG-unsafe|EBG-EBG-noR3|EB-T|EB-G|LG-LA|EBG-R ", r)]
    prim = [r for r in rows[:2]] + [r for r in rows[2:] if re.search(r"^\| (EBG-RT|EBG-T|EBG-LG|EBG-B) \|", r)]
    (d / "STATISTICAL_RESULTS.md").write_text("# Statistical results (confirmatory, eval3)\n\n" + note +
        "## Four primary comparisons (Holm over four; pooled over primary cells; family = category x attribute)\n\n" + "\n".join(prim) +
        "\n\n## All paired contrasts (non-primary rows are exploratory, BH)\n\n" + contrasts +
        "\n\n## Sensitivity: annotator-agreed items\n\n" + (sens or "(not run)") + "\n", encoding="utf-8")
    (d / "MODEL_COMPARISON.md").write_text("# Model comparison\n\n" + note + "## Per model and configuration\n\n" +
        section(conf, "Per model and configuration") + "\n\n## Per category\n\n" + section(conf, "Per category") +
        "\n\n## Secondary cells (Qwen2.5-14B, Llama-3.2-3B; never pooled)\n\n" + (sec or "(not run)") + "\n", encoding="utf-8")
    (d / "ABLATION_RESULTS.md").write_text("# Component ablations\n\n" + note + "\n".join(abl) + "\n", encoding="utf-8")
    (d / "LATENCY_AND_COST.md").write_text("# Latency and token overhead\n\n" + note + (met.split("\n", 2)[2] if met else "(no metrics)") + "\n", encoding="utf-8")
    (d / "EXPERIMENT_EXECUTION_LOG.md").write_text("# Experiment execution log\n\nSlurm array 4233 (submitted 2026-11-17 08:5x UTC), retry controller 4243, one GPU at a time. Cluster logs are in `logs/`; manifests per cell in RAW_RESULTS.\n\n" + comp +
        "\n## Notes\n\n(add: GPU-hours per cell from manifests/logs, resubmissions, incidents)\n", encoding="utf-8")
    print("wrote reports to", d)


if __name__ == "__main__":
    main()
